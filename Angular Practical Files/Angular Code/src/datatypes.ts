// String
let studentName: string = "Dhruval";

// Number
let age: number = 21;

// Boolean
let isStudent: boolean = true;

// Array
let subjects: string[] = ["Angular", "TypeScript", "HTML", "CSS"];

// Tuple
let studentInfo: [number, string] = [101, "Dhruval"];

// Any
let data: any = "Hello";
data = 500;
data = false;

// Unknown
let value: unknown = "Angular";

console.log("String:", studentName);
console.log("Number:", age);
console.log("Boolean:", isStudent);
console.log("Array:", subjects);
console.log("Tuple:", studentInfo);
console.log("Any:", data);
console.log("Unknown:", value);